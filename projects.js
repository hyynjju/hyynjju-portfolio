window.imageFormatFallback = (image) => {
  if (image.dataset.jpgFallback) {
    image.remove();
    return;
  }
  image.dataset.jpgFallback = 'true';
  image.src = image.src.replace(/\.png(?=$|[?#])/i, '.jpg');
};

document.addEventListener('contextmenu', (event) => {
  if (event.target instanceof Element && event.target.closest('img')) event.preventDefault();
}, true);

document.addEventListener('dragstart', (event) => {
  if (event.target instanceof HTMLImageElement) event.preventDefault();
}, true);

